import { parseRangeText, parseResumeText } from '../import-export/resume-parser';
import { RenderModel } from '../render-model/render-model.types';
import { AdapterOutput, AdapterSummary, Category, Finding, Indicator, ParserAdapter, ParsingReport, RunResult, SCORE_VERSION, Severity, SUITE_VERSION, FileKind } from './types';

/** Parsing Test Score weights (doc 21 s.6). Calibrate with fixtures; bump SCORE_VERSION when changed. */
export const WEIGHTS = { textCoverage: 0.25, sectionRecognition: 0.20, fieldRecognition: 0.20, readingOrder: 0.15, dates: 0.10, linksUnicode: 0.05, layout: 0.05 } as const;

const EMAIL = /[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/i;
const PHONE = /\+?\d[\d\s().-]{7,}\d/;
const norm = (s: string) => s.normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
const digits = (s: string) => s.replace(/\D/g, '');
const cap = (s: string | undefined, n = 80) => (s && s.length > n ? `${s.slice(0, n)}...` : s);
const tokens = (s: string) => norm(s).split(' ').filter((t) => t.length >= 2);

export interface Expected {
  name: string; email?: string; phone?: string; urls: string[];
  sections: Array<{ type: string; title: string }>;
  experiences: Array<{ title: string; employer: string; start?: string; end?: string; current: boolean }>;
  educations: Array<{ institution: string; title: string }>;
  skills: string[];
  markers: string[];
  text: string;
}

/** Ground truth derived from the render model of a resume generated by this platform. */
export function expectedFrom(m: RenderModel): Expected {
  const email = m.header.contacts.find((c) => EMAIL.test(c));
  const phone = m.header.contacts.find((c) => !EMAIL.test(c) && PHONE.test(c));
  const exp: Expected = {
    name: m.header.name, email, phone, urls: m.header.links.map((l) => l.url), sections: [], experiences: [], educations: [], skills: [], markers: [m.header.name], text: '',
  };
  const all: string[] = [m.header.name, m.header.headline ?? '', ...m.header.contacts, ...m.header.links.map((l) => `${l.label} ${l.url}`)];
  for (const s of m.sections) {
    exp.sections.push({ type: s.type, title: s.title }); exp.markers.push(s.title); all.push(s.title, s.text ?? '');
    for (const it of s.items ?? []) {
      all.push(it.title ?? '', it.subtitle ?? '', it.meta ?? '', it.text ?? '', ...(it.bullets ?? []), ...(it.tags ?? []), it.url ?? '');
      if (it.title) exp.markers.push(it.title);
      if (s.type === 'experience') {
        const r = it.meta ? parseRangeText(it.meta) : undefined;
        exp.experiences.push({ title: it.title ?? '', employer: (it.subtitle ?? '').split(',')[0].trim(), start: r?.start, end: r?.end, current: !!r?.current });
      }
      if (s.type === 'education') exp.educations.push({ institution: it.subtitle ?? '', title: it.title ?? '' });
      if (s.type === 'skills') exp.skills.push(...(it.tags ?? []));
    }
  }
  exp.text = all.join(' ');
  return exp;
}

/* ----------------------------- findings helper ----------------------------- */
class Findings {
  list: Finding[] = [];
  constructor(private adapter: string) {}
  add(id: string, category: Category, severity: Severity, message: string, extra: Partial<Finding> = {}) { this.list.push({ id, category, severity, adapter: this.adapter, message, ...extra }); }
}

/* ----------------------------- layout diagnostics ----------------------------- */
function layoutFindings(out: AdapterOutput, f: Findings): number {
  const L = out.layout; let penalty = 0;
  if (L.columns > 1) { penalty += 0.4; f.add('PT-LAY-001', 'layout', 'warning', 'This file appears to use more than one column. Parsers often merge columns line by line and mix up the order.', { suggestion: 'Use a single-column template for applications that are read by software.' }); }
  if (L.tables > 0) { penalty += 0.3; f.add('PT-LAY-002', 'layout', 'warning', `Found ${L.tables} table(s). Some parsers read tables cell by cell or skip them.`, { suggestion: 'Replace tables with plain paragraphs and tab stops.' }); }
  if (L.textBoxes > 0) { penalty += 0.3; f.add('PT-LAY-003', 'layout', 'warning', `Found ${L.textBoxes} text box(es). Text inside boxes is skipped or duplicated by some parsers.`, { suggestion: 'Move the text into the normal page flow.' }); }
  if (L.headerFooterHasContact) { penalty += 0.2; f.add('PT-LAY-004', 'layout', 'warning', 'Contact details sit in the page header or footer, which many parsers ignore.', { suggestion: 'Put your name and contact details in the main body.' }); }
  else if (L.headerFooterText) f.add('PT-LAY-005', 'layout', 'info', 'The file has header or footer text. Parsers that read only the body will not see it.');
  if (L.images > 0) { penalty += 0.1; f.add('PT-LAY-006', 'layout', 'info', `The file contains ${L.images} image(s). Any text inside images cannot be read.`); }
  if (L.imageOnlyPages > 0) { penalty += 0.5; f.add('PT-PAG-001', 'pages', 'error', `${L.imageOnlyPages} page(s) contain images but almost no selectable text. A parser cannot read them without OCR.`, { suggestion: 'Export a text-based PDF instead of a scan or screenshot.' }); }
  if (L.blankPages > 0) { penalty += 0.2; f.add('PT-PAG-002', 'pages', 'warning', `${L.blankPages} blank page(s) were found.`, { suggestion: 'Remove the empty page or tighten spacing so content ends before the page break.' }); }
  if (out.replacementChars > 0) { penalty += 0.2; f.add('PT-UNI-002', 'links-unicode', 'error', `${out.replacementChars} unreadable character(s) were extracted (font encoding problem).`, { suggestion: 'Use a standard font and export again.' }); }
  return Math.max(0, 1 - penalty);
}

/* ----------------------------- comparison with a known source ----------------------------- */
function compare(exp: Expected, out: AdapterOutput, s: ReturnType<typeof parseResumeText>, f: Findings) {
  const extractedText = out.lines.join(' ');
  const lines = out.lines.map(norm);

  // text coverage
  const have = new Set(tokens(extractedText)); const want = [...new Set(tokens(exp.text))];
  const missing = want.filter((t) => !have.has(t));
  const textCoverage = want.length ? 1 - missing.length / want.length : 1;
  if (textCoverage < 0.98) f.add('PT-TEXT-001', 'text', textCoverage < 0.8 ? 'error' : 'warning', `${Math.round((1 - textCoverage) * 100)}% of the words in your resume were not found in the extracted text.`, { expected: cap(missing.slice(0, 8).join(', ')), suggestion: 'Check for text in images, text boxes or unusual fonts, then re-export.' });

  // sections
  const found = new Set(s.sectionsFound);
  const secMissing = exp.sections.filter((x) => x.type !== 'summary' || true).filter((x) => !found.has(x.type));
  for (const m of secMissing) f.add('PT-SEC-001', 'sections', 'warning', `This parser did not detect your "${m.title}" heading.`, { section: m.type, expected: m.title, suggestion: 'Use a standard heading name and keep it on its own line.' });
  const sectionRecognition = exp.sections.length ? 1 - secMissing.length / exp.sections.length : 1;

  // fields
  let want_f = 0; let got_f = 0;
  const check = (ok: boolean, id: string, label: string, expected: string | undefined, extracted: string | undefined) => {
    want_f++; if (ok) got_f++; else f.add(id, 'fields', 'warning', `This parser did not detect your ${label}.`, { expected: cap(expected), extracted: cap(extracted) });
  };
  check(norm(s.fullName ?? '') === norm(exp.name), 'PT-FLD-001', 'name', exp.name, s.fullName);
  if (exp.email) check((s.email ?? '').toLowerCase() === exp.email.toLowerCase() || norm(extractedText).includes(norm(exp.email)), 'PT-FLD-002', 'email address', exp.email, s.email);
  if (exp.phone) check(digits(s.phone ?? '') === digits(exp.phone) || digits(extractedText).includes(digits(exp.phone)), 'PT-FLD-003', 'phone number', exp.phone, s.phone);
  for (const e of exp.experiences) {
    const hit = s.experiences.find((x) => norm(x.employerName) === norm(e.employer) || norm(x.jobTitle) === norm(e.title));
    check(!!hit && norm(hit.employerName) === norm(e.employer) && norm(hit.jobTitle) === norm(e.title), 'PT-FLD-004', `role "${e.title}" at "${e.employer}"`, `${e.title} - ${e.employer}`, hit ? `${hit.jobTitle} - ${hit.employerName}` : undefined);
  }
  for (const ed of exp.educations) {
    const hit = s.educations.find((x) => norm(x.institution).includes(norm(ed.institution)) || norm(ed.institution).includes(norm(x.institution)));
    check(!!hit && norm(ed.institution) !== '', 'PT-FLD-005', `education at "${ed.institution}"`, ed.institution, hit?.institution);
  }
  if (exp.skills.length) {
    const got = new Set(s.skills.map((k) => norm(k.name)));
    const sk = exp.skills.filter((k) => got.has(norm(k)));
    want_f += exp.skills.length; got_f += sk.length;
    if (sk.length < exp.skills.length) f.add('PT-FLD-006', 'fields', 'warning', `${exp.skills.length - sk.length} of ${exp.skills.length} skills were not recognised as skills.`, { expected: cap(exp.skills.filter((k) => !got.has(norm(k))).slice(0, 6).join(', ')) });
  }
  const fieldRecognition = want_f ? got_f / want_f : 1;

  // reading order: markers must appear in the source sequence
  const idx = exp.markers.map((m) => { const n = norm(m); return n ? lines.findIndex((l) => l.includes(n)) : -1; });
  const present = idx.map((i, k) => ({ i, k })).filter((x) => x.i >= 0);
  let inOrder = 0; let pairs = 0; const inversions: string[] = [];
  for (let a = 1; a < present.length; a++) { pairs++; if (present[a].i >= present[a - 1].i) inOrder++; else inversions.push(`"${cap(exp.markers[present[a].k], 40)}" comes before "${cap(exp.markers[present[a - 1].k], 40)}"`); }
  const readingOrder = pairs ? inOrder / pairs : 1;
  if (inversions.length) f.add('PT-ORD-001', 'reading-order', readingOrder < 0.8 ? 'error' : 'warning', 'Some content is read in a different order than it appears in your resume.', { extracted: cap(inversions.slice(0, 3).join('; '), 160), suggestion: 'Avoid columns, text boxes and floating elements so the reading order follows the page.' });

  // dates & chronology
  let dWant = 0; let dGot = 0;
  for (const e of exp.experiences) {
    if (!e.start) continue; dWant++;
    const hit = s.experiences.find((x) => norm(x.employerName) === norm(e.employer));
    const ok = !!hit && hit.startDate === e.start && (e.current ? hit.isCurrent : hit.endDate === e.end);
    if (ok) dGot++; else f.add('PT-DATE-001', 'dates', 'warning', `The dates for "${e.title}" were not read correctly.`, { expected: `${e.start} to ${e.current ? 'present' : e.end}`, extracted: hit ? `${hit.startDate} to ${hit.isCurrent ? 'present' : hit.endDate ?? '?'}` : 'role not found' });
  }
  const dates = dWant ? dGot / dWant : 1;

  // links + unicode
  const checks: boolean[] = [];
  const blob = extractedText.toLowerCase() + ' ' + out.links.join(' ').toLowerCase();
  for (const u of exp.urls) { const ok = blob.includes(u.toLowerCase().replace(/^https?:\/\//, '')); checks.push(ok); if (!ok) f.add('PT-LNK-001', 'links-unicode', 'warning', 'A link in your resume was not preserved.', { expected: cap(u) }); }
  const nonAscii = [...new Set([...exp.text].filter((c) => c.charCodeAt(0) > 127 && /\p{L}/u.test(c)))];
  if (nonAscii.length) {
    const lost = nonAscii.filter((c) => !extractedText.includes(c));
    checks.push(lost.length === 0);
    if (lost.length) f.add('PT-UNI-001', 'links-unicode', 'warning', 'Some non-English characters were lost or changed.', { expected: lost.slice(0, 10).join(' ') });
  }
  const linksUnicode = checks.length ? checks.filter(Boolean).length / checks.length : 1;

  return { textCoverage, sectionRecognition, fieldRecognition, readingOrder, dates, linksUnicode };
}

/* ----------------------------- diagnostics for files with no known source ----------------------------- */
function diagnose(out: AdapterOutput, s: ReturnType<typeof parseResumeText>, f: Findings) {
  const words = out.lines.join(' ').split(/\s+/).filter(Boolean).length;
  if (words < 40) f.add('PT-TEXT-002', 'text', 'error', 'Very little text was extracted. The file may be scanned, image-based or protected.', { suggestion: 'Export a text-based file from the resume editor.' });
  if (!s.fullName) f.add('PT-FLD-010', 'fields', 'warning', 'This parser could not find a name at the top of the file.');
  if (!s.email) f.add('PT-FLD-011', 'fields', 'warning', 'This parser did not detect an email address.');
  if (!s.phone) f.add('PT-FLD-012', 'fields', 'info', 'This parser did not detect a phone number.');
  for (const key of ['experience', 'education', 'skills'] as const) if (!s.sectionsFound.includes(key)) f.add('PT-SEC-010', 'sections', 'warning', `This parser did not detect a ${key[0].toUpperCase()}${key.slice(1)} heading.`, { section: key, suggestion: 'Use a standard heading name on its own line.' });
  if (s.experiences.length && s.experiences.some((e) => !e.startDate)) f.add('PT-DATE-010', 'dates', 'warning', 'Some roles have no readable start date.');
}

/* ----------------------------- agreement between reading strategies ----------------------------- */
/** Longest-common-subsequence ratio of normalised lines (capped) between two readers of the same file. */
export function agreement(a: string[], b: string[]): number {
  const x = a.map(norm).filter(Boolean).slice(0, 250); const y = b.map(norm).filter(Boolean).slice(0, 250);
  if (!x.length || !y.length) return 1;
  const dp = Array.from({ length: x.length + 1 }, () => new Array<number>(y.length + 1).fill(0));
  for (let i = 1; i <= x.length; i++) for (let j = 1; j <= y.length; j++) dp[i][j] = x[i - 1] === y[j - 1] ? dp[i - 1][j - 1] + 1 : Math.max(dp[i - 1][j], dp[i][j - 1]);
  return dp[x.length][y.length] / Math.max(x.length, y.length);
}

const ind = (ok: boolean, warn = false): Indicator => (ok ? 'ok' : warn ? 'warning' : 'problem');

/** Orchestrate adapters over one file (bytes stay in memory). `expected` is set only for resumes generated here. */
export async function runParsingTest(buf: Buffer, kind: FileKind, adapters: ParserAdapter[], expected?: Expected): Promise<RunResult> {
  const findings: Finding[] = []; const summaries: AdapterSummary[] = []; const preview: RunResult['preview'] = [];
  const outputs: Array<{ a: ParserAdapter; out: AdapterOutput }> = [];

  for (const a of adapters) {
    const base = { id: a.id, name: a.name, version: a.version, capabilities: a.capabilities };
    try {
      const out = await a.parse(buf);
      const s = parseResumeText(out.lines);
      const f = new Findings(a.id);
      const layoutScore = layoutFindings(out, f);
      let score: number | null = null; let breakdown: AdapterSummary['breakdown'] = null;
      if (expected) {
        const d = compare(expected, out, s, f);
        const parts = { ...d, layout: layoutScore };
        breakdown = Object.fromEntries((Object.keys(WEIGHTS) as Array<keyof typeof WEIGHTS>).map((k) => [k, { score: Math.round(parts[k] * 100), weight: WEIGHTS[k] }]));
        score = Math.round((Object.keys(WEIGHTS) as Array<keyof typeof WEIGHTS>).reduce((t, k) => t + parts[k] * WEIGHTS[k], 0) * 100);
      } else diagnose(out, s, f);
      findings.push(...f.list);
      outputs.push({ a, out });
      preview.push({ adapter: a.id, lines: out.lines.slice(0, 80) });
      summaries.push({
        ...base, lineCount: out.lines.length, wordCount: out.lines.join(' ').split(/\s+/).filter(Boolean).length, sectionsFound: s.sectionsFound,
        fields: { name: !!s.fullName, email: !!s.email, phone: !!s.phone, experienceEntries: s.experiences.length, educationEntries: s.educations.length, skills: s.skills.length },
        layout: out.layout, score, breakdown,
      });
    } catch (e) {
      const msg = (e as { message?: string }).message ?? 'This parser failed.';
      summaries.push({ ...base, lineCount: 0, wordCount: 0, sectionsFound: [], fields: { name: false, email: false, phone: false, experienceEntries: 0, educationEntries: 0, skills: 0 }, layout: { columns: 1, tables: 0, textBoxes: 0, images: 0, headerFooterText: false, headerFooterHasContact: false, blankPages: 0, imageOnlyPages: 0 }, score: null, breakdown: null, error: msg });
      findings.push({ id: 'PT-RUN-001', category: 'text', severity: 'error', adapter: a.id, message: `${a.name} could not read this file: ${msg}` });
    }
  }

  // disagreement between independent readers (doc 30): report, do not emulate any ATS
  let agree = 1;
  if (outputs.length > 1) {
    agree = agreement(outputs[0].out.lines, outputs[1].out.lines);
    if (agree < 0.85) findings.push({ id: 'PT-AGR-001', category: 'agreement', severity: agree < 0.6 ? 'error' : 'warning', message: `Two independent readers disagree about this file (${Math.round(agree * 100)}% of lines match in the same order).`, suggestion: 'Different parsers may read this document differently. Simplify the layout and test again.' });
  }

  const ok = summaries.filter((s) => !s.error);
  const scored = ok.filter((s) => s.score !== null);
  const score = expected && scored.length ? Math.round(scored.reduce((t, s) => t + (s.score as number), 0) / scored.length) : null;
  const has = (cat: Category, sev: Severity[]) => findings.some((f) => f.category === cat && sev.includes(f.severity));
  const textErr = !ok.length || findings.some((f) => (f.id === 'PT-TEXT-001' && f.severity === 'error') || f.id === 'PT-TEXT-002' || f.id === 'PT-PAG-001');
  const report: ParsingReport = {
    suiteVersion: SUITE_VERSION, scoreVersion: SCORE_VERSION, source: expected ? 'GENERATED' : 'UPLOAD', format: kind, generatedAt: new Date().toISOString(), score,
    scoreNote: expected
      ? 'Parsing Test Score compares what these test parsers extracted with the resume you generated. It is separate from the quality and job match scores and does not predict how any employer system will read the file.'
      : 'No score is shown: there is no known source to compare against, so an accuracy percentage would be invented. Only extraction diagnostics are reported.',
    indicators: {
      textExtracted: ind(!textErr, ok.some((s) => s.wordCount >= 40)),
      fieldsDetected: ok.length ? ind(ok.every((s) => s.fields.name && s.fields.email), ok.some((s) => s.fields.name)) : 'unknown',
      readingOrder: outputs.length > 1 ? ind(agree >= 0.85 && !has('reading-order', ['error', 'warning']), agree >= 0.6 && !has('reading-order', ['error'])) : has('reading-order', ['error', 'warning']) ? 'warning' : 'unknown',
      layout: has('layout', ['warning']) || has('pages', ['error']) ? (has('pages', ['error']) ? 'problem' : 'warning') : 'ok',
    },
    adapters: summaries, findings: dedupe(findings),
    limitations: [
      'These are independent test parsers built for this product. They do not emulate any employer ATS or its ranking.',
      'Scanned or image-only documents cannot be read (no OCR).',
      'Only the first 10 pages are tested.',
      'Results show what these parsers extracted; they are not a hiring or ATS-compatibility guarantee.',
    ],
  };
  return { report, preview };
}

/** The same rule firing for several adapters is shown once per adapter only when messages differ. */
function dedupe(list: Finding[]): Finding[] {
  const seen = new Set<string>(); const out: Finding[] = [];
  for (const f of list) { const k = `${f.id}|${f.message}|${f.section ?? ''}|${f.adapter}`; if (!seen.has(k)) { seen.add(k); out.push(f); } }
  const order: Record<Severity, number> = { error: 0, warning: 1, info: 2 };
  return out.sort((a, b) => order[a.severity] - order[b.severity] || a.id.localeCompare(b.id));
}
